use crate::browser::{
    file_browser_parts, sort_markdown_files, truncate_for_width, FileBrowserState,
};
use crate::display::{Display, RefreshMode};
use crate::font::Font;
use crate::hardware::Hardware;
use crate::input::Button;
use crate::power::{PowerManager, POWER_BUTTON_SLEEP_MS};
use crate::reader::{
    ReaderCache, ReaderPaginator, ReaderState, READER_RIGHT_MARGIN, READER_TEXT_Y, READER_X,
};
use crate::time::now_ms;
use anyhow::Result;
use log::{info, warn};

const DEFAULT_LOOP_DELAY_MS: u32 = 5;
const IDLE_LOOP_DELAY_MS: u32 = 50;
const LIST_TOP_Y: usize = 28;
const LIST_BOTTOM_MARGIN: usize = 36;
const LIST_X: usize = 48;
const LIST_RIGHT_MARGIN: usize = 24;
const INPUT_STARTUP_IGNORE_MS: u64 = 300;
const BROWSER_REPEAT_START_MS: u32 = 280;
const BROWSER_REPEAT_INTERVAL_MS: u64 = 140;
const READER_REPEAT_START_MS: u32 = 500;
const READER_REPEAT_INTERVAL_MS: u64 = 450;

// Generated by tools/generate_font.py
static FONT_16_DATA: &[u8] = include_bytes!("../generated/font_16.bin");
static FONT_18_DATA: &[u8] = include_bytes!("../generated/font_18.bin");

#[derive(Clone, Copy, Debug)]
enum Activity {
    FileBrowser(FileBrowserState),
    Reader(ReaderState),
}

pub struct ReaderApp {
    hardware: Hardware,
    display: Display,
    ui_font: Font,
    reader_font: Font,
    power: PowerManager,
    idle_ticks: u32,
    md_files: Vec<String>,
    activity: Activity,
    reader_cache: Option<ReaderCache>,
    input_ignore_until_ms: u64,
    input_locked_until_release: bool,
    browser_last_repeat_ms: u64,
    reader_last_repeat_ms: u64,
}

impl ReaderApp {
    pub fn boot(mut hardware: Hardware, mut display: Display) -> Result<Self> {
        info!("Booting rr_reader");

        hardware.mount_storage()?;
        display.begin()?;

        let ui_font = Font::new(FONT_16_DATA)?;
        let reader_font = Font::new(FONT_18_DATA)?;
        info!(
            "UI font loaded: {}x{}px, {} glyphs",
            ui_font.glyph_width, ui_font.glyph_height, ui_font.glyph_count
        );
        info!(
            "Reader font loaded: {}x{}px, {} glyphs",
            reader_font.glyph_width, reader_font.glyph_height, reader_font.glyph_count
        );

        // Scan vault for markdown files
        let mut md_files = match hardware.storage.list_markdown_files("") {
            Ok(files) => files,
            Err(e) => {
                warn!("Failed to scan vault: {}", e);
                Vec::new()
            }
        };
        sort_markdown_files(&mut md_files);
        info!("Found {} markdown files in vault", md_files.len());

        // Show boot screen with status
        display.show_boot_screen()?;
        display.draw_text_font(&ui_font, &format!("文件: {}", md_files.len()), 220, 280);
        display.flush_with_mode(RefreshMode::Full)?;

        info!("Boot complete");

        let mut app = Self {
            hardware,
            display,
            ui_font,
            reader_font,
            power: PowerManager::new(),
            idle_ticks: 0,
            md_files,
            activity: Activity::FileBrowser(FileBrowserState {
                selected: 0,
                first_visible: 0,
            }),
            reader_cache: None,
            input_ignore_until_ms: now_ms() + INPUT_STARTUP_IGNORE_MS,
            input_locked_until_release: true,
            browser_last_repeat_ms: 0,
            reader_last_repeat_ms: 0,
        };
        app.render_current_activity();
        app.flush_ui_refresh();
        Ok(app)
    }

    pub fn tick(&mut self) -> Result<()> {
        self.hardware.update_inputs();

        let has_activity = self.hardware.has_user_activity();
        if has_activity {
            self.idle_ticks = 0;
            self.power.mark_activity();
        } else {
            self.idle_ticks = self.idle_ticks.saturating_add(1);
            self.power.tick();
        }

        if now_ms() < self.input_ignore_until_ms {
            self.hardware.input.clear_events();
            self.flush_display_if_dirty()?;
            return Ok(());
        }

        if self.input_locked_until_release {
            self.hardware.input.clear_events();
            if self.hardware.input.any_pressed() {
                self.flush_display_if_dirty()?;
                return Ok(());
            }
            self.input_locked_until_release = false;
            self.flush_display_if_dirty()?;
            return Ok(());
        }

        self.handle_input()?;

        // Flush display if dirty
        self.flush_display_if_dirty()?;

        // Auto-sleep
        if self.power.should_sleep() {
            info!("Auto-sleep after {} idle ticks", self.idle_ticks);
            self.power.enter_deep_sleep(None);
        }

        Ok(())
    }

    fn handle_input(&mut self) -> Result<()> {
        use Button::*;

        if self
            .hardware
            .input
            .long_pressed_once(crate::input::BTN_POWER, POWER_BUTTON_SLEEP_MS)
        {
            info!("Power long press -> sleep");
            self.power.enter_deep_sleep(None);
            return Ok(());
        }

        match self.activity {
            Activity::FileBrowser(_) => {
                let next_buttons = [Down, Right];
                let previous_buttons = [Up, Left];

                if let Some(delta) = self.navigation_delta(
                    &next_buttons,
                    &previous_buttons,
                    BROWSER_REPEAT_START_MS,
                    BROWSER_REPEAT_INTERVAL_MS,
                    self.browser_last_repeat_ms,
                ) {
                    self.move_browser_selection(delta);
                    self.browser_last_repeat_ms = now_ms();
                    return Ok(());
                }

                if !self
                    .hardware
                    .input
                    .any_logical_is_pressed(&[Down, Right, Up, Left])
                {
                    self.browser_last_repeat_ms = 0;
                }

                if self.hardware.input.logical_was_pressed(Confirm) {
                    self.open_selected_file();
                    return Ok(());
                }
            }
            Activity::Reader(reader) => {
                if self.hardware.input.logical_was_released(Back) {
                    self.activity = Activity::FileBrowser(FileBrowserState {
                        selected: reader.file_index,
                        first_visible: self.browser_first_visible_for(reader.file_index),
                    });
                    self.render_file_browser();
                    self.flush_ui_refresh();
                    return Ok(());
                }

                if let Some(delta) = self.navigation_delta(
                    &[PageForward, Right],
                    &[PageBack, Left],
                    READER_REPEAT_START_MS,
                    READER_REPEAT_INTERVAL_MS,
                    self.reader_last_repeat_ms,
                ) {
                    self.move_reader_page(delta);
                    self.reader_last_repeat_ms = now_ms();
                    return Ok(());
                }

                if !self.hardware.input.any_logical_is_pressed(&[
                    PageForward,
                    Right,
                    PageBack,
                    Left,
                ]) {
                    self.reader_last_repeat_ms = 0;
                }

                if self.hardware.input.logical_was_pressed(Confirm) {
                    self.render_current_file();
                    self.flush_ui_refresh();
                    return Ok(());
                }
            }
        }

        Ok(())
    }

    fn render_current_activity(&mut self) {
        match self.activity {
            Activity::FileBrowser(_) => self.render_file_browser(),
            Activity::Reader(_) => self.render_current_file(),
        }
    }

    fn move_browser_selection(&mut self, delta: isize) {
        if self.md_files.is_empty() {
            return;
        }

        let file_count = self.md_files.len();
        let selected = match &self.activity {
            Activity::FileBrowser(browser) => browser.selected,
            _ => return,
        };
        let next = (selected as isize + delta).rem_euclid(file_count as isize) as usize;
        self.set_browser_selection(next);
        self.render_file_browser();
        self.flush_ui_refresh();
    }

    fn move_browser_page(&mut self, delta: isize) {
        if self.md_files.is_empty() {
            return;
        }

        let row_count = self.browser_row_count().max(1);
        let file_count = self.md_files.len();
        if file_count <= row_count {
            self.move_browser_selection(delta.signum());
            return;
        }

        let selected = match &self.activity {
            Activity::FileBrowser(browser) => browser.selected,
            _ => return,
        };
        let current_page = selected / row_count;
        let last_page = (file_count - 1) / row_count;
        let next = if delta.is_negative() {
            if current_page > 0 {
                (current_page - 1) * row_count
            } else {
                last_page * row_count
            }
        } else if current_page < last_page {
            (current_page + 1) * row_count
        } else {
            0
        };

        self.set_browser_selection(next.min(file_count - 1));
        self.render_file_browser();
        self.flush_ui_refresh();
    }

    fn set_browser_selection(&mut self, selected: usize) {
        let row_count = self.browser_row_count().max(1);

        if let Activity::FileBrowser(browser) = &mut self.activity {
            browser.selected = selected;
            if browser.selected < browser.first_visible {
                browser.first_visible = browser.selected;
            } else if browser.selected >= browser.first_visible + row_count {
                browser.first_visible = browser.selected + 1 - row_count;
            }
        }
    }

    fn open_selected_file(&mut self) {
        let file_index = match &self.activity {
            Activity::FileBrowser(browser) if !self.md_files.is_empty() => browser.selected,
            _ => return,
        };

        self.activity = Activity::Reader(ReaderState {
            file_index,
            page_index: 0,
        });
        self.render_current_file();
        self.flush_ui_refresh();
    }

    fn navigation_delta(
        &self,
        next_buttons: &[Button],
        previous_buttons: &[Button],
        repeat_start_ms: u32,
        repeat_interval_ms: u64,
        last_repeat_ms: u64,
    ) -> Option<isize> {
        if self.hardware.input.any_logical_pressed(next_buttons) {
            return Some(1);
        }
        if self.hardware.input.any_logical_pressed(previous_buttons) {
            return Some(-1);
        }

        let next_held = self.hardware.input.any_logical_is_pressed(next_buttons);
        let previous_held = self.hardware.input.any_logical_is_pressed(previous_buttons);
        if !next_held && !previous_held {
            return None;
        }

        let now = now_ms();
        if now.saturating_sub(last_repeat_ms) < repeat_interval_ms {
            return None;
        }

        if next_held && self.hardware.input.any_logical_held_ms(next_buttons) >= repeat_start_ms {
            return Some(1);
        }
        if previous_held
            && self.hardware.input.any_logical_held_ms(previous_buttons) >= repeat_start_ms
        {
            return Some(-1);
        }

        None
    }

    fn move_reader_page(&mut self, delta: isize) {
        let reader = match self.activity {
            Activity::Reader(reader) => reader,
            _ => return,
        };

        if self.ensure_reader_cache(reader.file_index).is_err() {
            return;
        }

        let page_count = self.reader_page_count().max(1);
        let next = if delta.is_negative() {
            reader
                .page_index
                .saturating_sub(delta.unsigned_abs().min(reader.page_index))
        } else {
            reader
                .page_index
                .saturating_add(delta as usize)
                .min(page_count - 1)
        };

        if next == reader.page_index {
            return;
        }

        self.activity = Activity::Reader(ReaderState {
            file_index: reader.file_index,
            page_index: next,
        });
        self.render_current_file();
        self.flush_ui_refresh();
    }

    fn flush_ui_refresh(&mut self) {
        if let Err(e) = self.flush_display_if_dirty() {
            warn!("Interactive refresh failed: {}", e);
        }
    }

    fn flush_display_if_dirty(&mut self) -> Result<()> {
        let input = &mut self.hardware.input;
        self.display
            .flush_if_dirty_polling(|| input.poll_during_blocking_wait())
    }

    fn render_file_browser(&mut self) {
        self.display.clear(0xFF);

        if self.md_files.is_empty() {
            self.display.draw_text_wrapped(
                &self.ui_font,
                "没有笔记",
                LIST_X,
                LIST_TOP_Y,
                Display::width() - LIST_RIGHT_MARGIN,
                4,
            );
            info!("Rendering empty file browser");
            return;
        }

        let (selected, first_visible) = match &self.activity {
            Activity::FileBrowser(browser) => (browser.selected, browser.first_visible),
            Activity::Reader(reader) => (
                reader.file_index,
                self.browser_first_visible_for(reader.file_index),
            ),
        };

        let row_height = self.browser_row_height();
        let row_count = self.browser_row_count();
        let end = (first_visible + row_count).min(self.md_files.len());

        for (row, idx) in (first_visible..end).enumerate() {
            let y = LIST_TOP_Y + row * row_height;
            let selected_row = idx == selected;
            if selected_row {
                self.display.fill_rect(24, y - 3, 4, row_height - 8, 0x00);
            }

            let (_, name) = file_browser_parts(&self.md_files[idx]);
            let name = truncate_for_width(
                &self.ui_font,
                name,
                Display::width() - LIST_X - LIST_RIGHT_MARGIN,
            );
            self.display.draw_text_font(&self.ui_font, &name, LIST_X, y);
        }

        let nav_hint = match (first_visible > 0, end < self.md_files.len()) {
            (true, true) => "↑↓",
            (true, false) => "↑",
            (false, true) => "↓",
            (false, false) => "",
        };
        let footer = if nav_hint.is_empty() {
            format!("{}/{}  OK", selected + 1, self.md_files.len())
        } else {
            format!("{}/{}  {}  OK", selected + 1, self.md_files.len(), nav_hint)
        };
        let footer_x = Display::width().saturating_sub(24 + self.ui_font.text_width(&footer));
        self.display.draw_text_font(
            &self.ui_font,
            &footer,
            footer_x,
            Display::height() - self.ui_font.glyph_height as usize - 8,
        );

        info!(
            "Rendering file browser: selected {}/{}",
            selected + 1,
            self.md_files.len()
        );
    }

    fn render_current_file(&mut self) {
        self.display.clear(0xFF);

        if self.md_files.is_empty() {
            self.display.draw_text_wrapped(
                &self.ui_font,
                "没有 Markdown 文件\n/sdcard/vault",
                24,
                20,
                Display::width() - 24,
                4,
            );
            info!("No files to render");
            return;
        }

        let reader = match &self.activity {
            Activity::Reader(reader) => Some(*reader),
            Activity::FileBrowser(_) => None,
        };

        let file_index = match self.activity {
            Activity::Reader(reader) => reader.file_index.min(self.md_files.len() - 1),
            Activity::FileBrowser(browser) => browser.selected.min(self.md_files.len() - 1),
        };
        let rel_path = self.md_files[file_index].clone();
        match self.ensure_reader_cache(file_index) {
            Ok(()) => {
                let cache = match self.reader_cache.as_ref() {
                    Some(cache) if cache.file_index == file_index => cache,
                    _ => return,
                };
                let page_count = cache.page_starts.len().max(1);
                let page_index = reader
                    .map(|reader| reader.page_index.min(page_count - 1))
                    .unwrap_or(0);
                if let Some(reader) = reader {
                    if page_index != reader.page_index {
                        self.activity = Activity::Reader(ReaderState {
                            file_index,
                            page_index,
                        });
                    }
                }

                let page_start = cache.page_starts.get(page_index).copied().unwrap_or(0);
                let page_end = cache
                    .page_starts
                    .get(page_index + 1)
                    .copied()
                    .unwrap_or(cache.file_len);
                let page_text = match self
                    .hardware
                    .storage
                    .read_markdown_range(&rel_path, page_start, page_end)
                {
                    Ok(page_text) => page_text,
                    Err(e) => {
                        self.display.draw_text_wrapped(
                            &self.ui_font,
                            &format!("Error reading {}:\n{}", rel_path, e),
                            24,
                            20,
                            Display::width() - 24,
                            4,
                        );
                        warn!("Failed to read {} page {}: {}", rel_path, page_index + 1, e);
                        return;
                    }
                };

                let (_, name) = file_browser_parts(&rel_path);
                let title = format!("[{}] {}", file_index + 1, name);
                let title = truncate_for_width(&self.ui_font, &title, Display::width() - 48);
                self.display
                    .draw_text_font(&self.ui_font, &title, READER_X, 10);
                self.display
                    .fill_rect(READER_X, 34, Display::width() - 48, 1, 0x00);
                self.display.draw_text_wrapped(
                    &self.reader_font,
                    &page_text,
                    READER_X,
                    READER_TEXT_Y,
                    Display::width() - READER_RIGHT_MARGIN,
                    5,
                );
                let footer = format!("{}/{}", page_index + 1, page_count);
                let footer_x =
                    Display::width().saturating_sub(READER_X + self.ui_font.text_width(&footer));
                self.display.draw_text_font(
                    &self.ui_font,
                    &footer,
                    footer_x,
                    Display::height() - self.ui_font.glyph_height as usize - 8,
                );
                info!(
                    "Rendering file {}/{} page {}/{}: {}",
                    file_index + 1,
                    self.md_files.len(),
                    page_index + 1,
                    page_count,
                    rel_path
                );
            }
            Err(e) => {
                self.display.draw_text_wrapped(
                    &self.ui_font,
                    &format!("Error reading {}:\n{}", rel_path, e),
                    24,
                    20,
                    Display::width() - 24,
                    4,
                );
                warn!("Failed to read {}: {}", rel_path, e);
            }
        }
    }

    fn ensure_reader_cache(&mut self, file_index: usize) -> Result<()> {
        if matches!(
            self.reader_cache,
            Some(ReaderCache {
                file_index: cached,
                ..
            }) if cached == file_index
        ) {
            return Ok(());
        }

        let rel_path = &self.md_files[file_index];
        let file_len = self.hardware.storage.markdown_file_len(rel_path)?;
        let page_starts = self.paginate_reader_file(rel_path, file_len)?;
        self.reader_cache = Some(ReaderCache {
            file_index,
            file_len,
            page_starts,
        });
        Ok(())
    }

    fn reader_page_count(&self) -> usize {
        self.reader_cache
            .as_ref()
            .map(|cache| cache.page_starts.len())
            .unwrap_or(0)
    }

    fn paginate_reader_file(&self, rel_path: &str, file_len: usize) -> Result<Vec<usize>> {
        let mut paginator = ReaderPaginator::new(&self.reader_font);
        self.hardware
            .storage
            .scan_markdown_chars(rel_path, |byte_index, ch| {
                paginator.push_char(byte_index, ch);
                Ok(())
            })?;
        Ok(paginator.finish(file_len))
    }

    fn browser_row_count(&self) -> usize {
        let row_height = self.browser_row_height();
        (Display::height() - LIST_TOP_Y - LIST_BOTTOM_MARGIN) / row_height
    }

    fn browser_row_height(&self) -> usize {
        self.ui_font.glyph_height as usize + 12
    }

    fn browser_first_visible_for(&self, selected: usize) -> usize {
        let row_count = self.browser_row_count().max(1);
        selected
            .saturating_sub(row_count / 2)
            .min(self.md_files.len().saturating_sub(row_count))
    }

    pub fn loop_delay_ms(&self) -> u32 {
        if self.idle_ticks > 500 {
            IDLE_LOOP_DELAY_MS
        } else {
            DEFAULT_LOOP_DELAY_MS
        }
    }
}
